/** `docs/deferred.md` is canonical for decisions; we only index it. */
function parseRegister(md) {
  const lines = md.split('\n');
  let section = null;
  const items = [];
  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const sec = /^##\s+(open|resolved)\s*$/i.exec(line);
    if (sec) {
      section = sec[1].toLowerCase();
      continue;
    }
    // Bullet summaries ("- **D-009** — …") live in the Resolved section and are
    // records too; index them so the count is not silently short.
    const bullet = section === 'resolved' ? /^-\s+\*\*(D-\d+)\*\*\s*[—-]\s*(.*)$/.exec(line) : null;
    if (bullet) {
      items.push({ id: bullet[1], title: bullet[2].replace(/\s*\(.*$/, '').trim(), section, status: 'resolved summary', resolved: true, revisit: '' });
      continue;
    }
    const head = /^###\s+(D-\d+)\s+·\s+(.*)$/.exec(line);
    if (!head) continue;
    let statusRaw = '';
    for (let j = i + 1; j < Math.min(i + 10, lines.length); j += 1) {
      if (/^###\s/.test(lines[j])) break;
      if (/^\*\*Status:\*\*/.test(lines[j])) {
        statusRaw = lines[j].replace(/^\*\*Status:\*\*\s*/, '').trim();
        break;
      }
    }
    // "Resolved" is a claim in the Status line; the section says where it belongs.
    const resolved = /✅|RESOLVED/i.test(statusRaw);
    const revisit = (/(?:^|·)\s*\*\*Revisit:\*\*\s*(.+)$/.exec(statusRaw) || [])[1] || '';
    items.push({
      id: head[1],
      title: head[2].trim(),
      section: section || 'unfiled',
      status: statusRaw,
      resolved,
      revisit: revisit.trim(),
    });
  }
  return items;
}

function parseRoadmap(md) {
  const phases = [];
  let current = null;
  for (const line of md.split('\n')) {
    const h = /^##\s+(.*)$/.exec(line);
    if (h) {
      if (!/^Phase\s+\d/i.test(h[1])) {
        current = null;
        continue;
      }
      const raw = h[1].replace(/\s+/g, ' ').trim();
      // A phase may declare completion in its heading, carry checkboxes, or be
      // prose-only. Never infer "not started" from a heading that says completed:
      // phases 1-3 track milestones in tables, not checkboxes.
      current = {
        name: raw.replace(/\*/g, '').replace(/\s*✅.*$/, '').trim(),
        headingSaysComplete: /✅|\bCompleted\b/i.test(raw),
        headingSaysCurrent: /\bCurrent Focus\b/i.test(raw),
        done: 0,
        todo: 0,
      };
      phases.push(current);
      continue;
    }
    if (!current) continue;
    if (/^\s*- \[x\]/i.test(line)) current.done += 1;
    else if (/^\s*- \[ \]/.test(line)) current.todo += 1;
  }
  return phases;
}

/**
 * docs/v2/BUILD.md is the v2 checklist ("- [x] 5. Feed and posts: ..."). FOUNDATION
 * section 12 says STATUS.md reads it, so the ledger shows v2 progress without a copy.
 */
function parseBuild(md) {
  const steps = [];
  for (const line of md.split('\n')) {
    const m = /^\s*- \[( |x)\]\s+(\d+)\.\s+(.*)$/i.exec(line);
    if (!m) continue;
    const text = m[3].trim();
    const title = text.split(/:\s/)[0].replace(/\*/g, '').trim();
    steps.push({ n: Number(m[2]), title, done: m[1].toLowerCase() === 'x' });
  }
  return steps;
}

/** Test cases as *declared in source* — deterministic, no test run needed. */
function countTests(dir) {
  const files = [];
  if (!existsSync(join(ROOT, dir))) return { files: 0, cases: 0 };
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (entry === 'node_modules' || entry.startsWith('.')) continue;
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.test\.tsx?$/.test(entry)) files.push(path);
    }
  };
  walk(join(ROOT, dir));
  let cases = 0;
  for (const file of files) {
    const body = readFileSync(file, 'utf8');
    cases += (body.match(/^\s*(?:it|test)(?:\.\w+)?\s*\(/gm) || []).length;
  }
  return { files: files.length, cases };
}

/** Which gates CI actually enforces — read from the workflow, not remembered. */
function parseCiGates() {
  const path = join(ROOT, '.github/workflows/ci.yml');
  if (!existsSync(path)) return [];
  const body = readFileSync(path, 'utf8');
  const gates = [];
  for (const m of body.matchAll(/-\s+name:\s*(.+)\n([\s\S]*?)(?=\n\s*-\s+name:|\n\s{0,4}\w+:\s*$|$)/g)) {
    const name = m[1].trim();
    // `run: |` opens a block scalar whose body is a script, not a gate name —
    // take the first real single-line command for the step and ignore the rest.
    const runs = [...m[2].matchAll(/run:\s*(.+)/g)]
      .map((x) => x[1].trim())
      .filter((cmd) => cmd && cmd !== '|' && cmd !== '>' && !cmd.startsWith('|'));
    const scripted = /run:\s*[|>]/.test(m[2]);
    gates.push({ name, runs: runs.slice(0, 1), scripted: scripted && runs.length === 0 });
  }
  return gates;
}

