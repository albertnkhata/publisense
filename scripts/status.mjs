#!/usr/bin/env node
/**
 * Publisense status ledger.
 *
 * WHY THIS EXISTS
 * ---------------
 * The registers drifted every time they were maintained by hand: a roadmap that
 * was four days stale and wrong in three places, resolved decisions sitting under
 * "Open", a test count that said 42 when the suite had 96. The fix is not better
 * discipline, it is deriving the status from the system instead of restating it.
 *
 * THREE LAYERS, ONE READING SURFACE
 * --------------------------------
 *   docs/archive/roadmap.md  v1 intent (frozen history; v1 was retired at the 2026-10-24 cutover)
 *   docs/v2/BUILD.md   v2 build  (hand-ticked checklist, one PR per step)
 *   docs/deferred.md   decisions (hand-written, D-xxx ids, never deleted)
 *   STATUS.md          ledger    (GENERATED by this script — do not hand-edit)
 *
 * The join keys are the ones already in the repo: `D-xxx`, issue `#n`, PR `#n`.
 * This script indexes them and adds only what the repo cannot say about itself.
 *
 * TWO BLOCKS, TWO UPDATE PATHS
 * ----------------------------
 *   repo-derived  Everything from files in the repo (register, roadmap, test
 *                 declarations, CI gates). Deterministic, no network, no secrets.
 *                 `--check` fails when the committed copy is stale, so staleness
 *                 shows up as a red check rather than as quiet rot.
 *   live          Production facts: served bundle, row counts, fixture split,
 *                 enabled providers, consent-screen branding, open issues/PRs.
 *                 Needs network and sometimes secrets, so a scheduled refresh
 *                 (--live) owns this block; `--check` never touches it.
 *
 * USAGE
 *   node scripts/status.mjs            regenerate the repo-derived block, keep last live block
 *   node scripts/status.mjs --live     also re-probe production (env may unlock more)
 *   node scripts/status.mjs --check    exit 1 if the committed ledger is stale (CI)
 *
 * No dependencies and no package.json: run it with plain `node` from the repo root.
 *
 * ENVIRONMENT (all optional; a missing one degrades to `unknown`, never to a guess)
 *   VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY  read from .env if unset
 *                                               (also read from web/.env, where v2 keeps them)
 *   SUPABASE_SERVICE_ROLE                       unlocks counts behind RLS and the auth user count
 *   VERCEL_TOKEN                                unlocks the deployed commit sha
 *   GH_TOKEN / gh auth                          unlocks open issues and PRs
 */

