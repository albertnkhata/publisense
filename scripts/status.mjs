if (MODE_CHECK) {
  const committed = existsSync(STATUS_MD) ? readFileSync(STATUS_MD, 'utf8') : '';
  // Compare the repo-derived block only: the live block moves on a different clock
  // and must not fail a PR for being a few minutes old.
  const slice = (text) => {
    const start = text.indexOf('<!-- status:repo-derived:start');
    const end = text.indexOf('<!-- status:repo-derived:end -->');
    return start === -1 || end === -1 ? '' : text.slice(start, end + '<!-- status:repo-derived:end -->'.length);
  };
  const want = slice(markdown);
  const have = slice(committed);
  if (!want || !have || want !== have) {
    console.error('status: STATUS.md is stale — run `node scripts/status.mjs` and commit the result.');
    console.error('--- committed ---');
    console.error(have || '(no repo-derived block found)');
    console.error('--- expected ---');
    console.error(want || '(could not render)');
    process.exit(1);
  }
  const ageDays = live && live.generatedAt ? (Date.now() - Date.parse(live.generatedAt)) / 86400000 : null;
  if (ageDays !== null && ageDays > 7) {
    console.warn(`status: live block is ${ageDays.toFixed(1)} days old — schedule a refresh (\`node scripts/status.mjs --live\`).`);
  }
  console.log('status: ledger up to date');
  process.exit(0);
}

writeFileSync(STATUS_MD, markdown);
